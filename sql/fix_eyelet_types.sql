-- แก้ประเภทม่านของออเดอร์เก่าที่ชื่อรายการไม่ได้บอกแบบม่าน → ม่านตาไก่
--
-- ที่มา: ตอนแปลงข้อความ ออเดอร์เก่าได้ชื่อกลางๆ ที่ไม่บอกแบบม่าน
--        user ไล่เช็คแล้ว = เป็นม่านตาไก่ทั้งหมด (2 ส.ค. 69)
--        ตรวจจากข้อมูลจริงแล้วไม่มีรายการชื่อกลางๆ ใบไหนที่เป็นจีบ/ลอนเทป/ลอนตะขอ/ซ่อนหู
--
-- ของที่จะถูกแก้ (นับจากฐานจริงวันที่ทำไฟล์ = 67 รายการใน 56 ออเดอร์):
--        ผ้าม่านหน้าต่าง   38 รายการ → ผ้าม่านตาไก่
--        ผ้าม่านโปร่ง      22 รายการ → ผ้าโปร่งตาไก่
--        ผ้าม่านโปร่งเรียบ  6 รายการ → ผ้าโปร่งตาไก่
--        ผ้าโปร่ง           1 รายการ → ผ้าโปร่งตาไก่
--
-- แตะเฉพาะช่องประเภทม่านของรายการที่ชื่อ "ตรงเป๊ะ" กับ 4 คำนี้เท่านั้น
-- (ผ้าโปร่งลอนเทป / ผ้าโปร่งตาไก่ / ชื่ออื่นๆ ไม่โดน) · สี รหัสสี ขนาด จำนวน ลำดับรายการ คงเดิม
-- รันซ้ำได้ (ครั้งที่ 2 จะไม่มีอะไรเปลี่ยน) · ตาราง claims ไม่มีรายการชื่อกลางๆ เลยไม่ต้องแก้
-- ‼️ รันใน Supabase → SQL Editor
-- ════════════════════════════════════════════════════════════════════════════

-- ===== 1) ดูก่อนว่ามีอะไรจะถูกแก้บ้าง (ไม่บังคับ) =====
select o.order_number, o.customer_name, o.created_at::date as วันที่,
       x.it->>'type' as "ชื่อเดิม",
       x.it->>'width' as "กว้าง", x.it->>'quantity' as "จำนวน"
  from order_entries o, jsonb_array_elements(o.items) x(it)
 where jsonb_typeof(o.items) = 'array'
   and x.it->>'type' in ('ผ้าม่านหน้าต่าง', 'ผ้าม่านโปร่ง', 'ผ้าม่านโปร่งเรียบ', 'ผ้าโปร่ง')
 order by o.created_at desc;

-- ===== 2) แก้จริง =====
update order_entries o
   set items = (
         select coalesce(jsonb_agg(
                  case
                    when e.it->>'type' = 'ผ้าม่านหน้าต่าง'
                      then jsonb_set(e.it, '{type}', '"ผ้าม่านตาไก่"'::jsonb)
                    when e.it->>'type' in ('ผ้าม่านโปร่ง', 'ผ้าม่านโปร่งเรียบ', 'ผ้าโปร่ง')
                      then jsonb_set(e.it, '{type}', '"ผ้าโปร่งตาไก่"'::jsonb)
                    else e.it
                  end order by e.ord), '[]'::jsonb)
           from jsonb_array_elements(o.items) with ordinality e(it, ord)
       ),
       updated_at = now()
 where jsonb_typeof(o.items) = 'array'
   and exists (
         select 1 from jsonb_array_elements(o.items) x(it)
          where x.it->>'type' in ('ผ้าม่านหน้าต่าง', 'ผ้าม่านโปร่ง', 'ผ้าม่านโปร่งเรียบ', 'ผ้าโปร่ง')
       );

-- ===== 3) ตรวจผล — ต้องได้ 0 =====
select count(*) as "เหลือชื่อกลางๆ"
  from order_entries o, jsonb_array_elements(o.items) x(it)
 where jsonb_typeof(o.items) = 'array'
   and x.it->>'type' in ('ผ้าม่านหน้าต่าง', 'ผ้าม่านโปร่ง', 'ผ้าม่านโปร่งเรียบ', 'ผ้าโปร่ง');

