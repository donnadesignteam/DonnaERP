// ค้นจังหวัดจากคำค้น (ว่าง = ทั้งหมด) — 3 อันดับแรกอยู่บนสุดเสมอ
export function searchProvinces(q: string): string[] {
  const s = q.trim().toLowerCase()
  if (!s) return PROVINCES
  return PROVINCES.filter(p => p.toLowerCase().includes(s) || (ALIAS[p] ?? '').includes(s))
}
