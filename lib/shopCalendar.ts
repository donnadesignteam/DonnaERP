// ช่องของปฏิทินเดือนนั้น (เริ่มวันจันทร์) — null = ช่องว่างนอกเดือน
export function monthCells(year: number, month: number): (number | null)[] {
  const dim = new Date(year, month + 1, 0).getDate()
  const first = (new Date(year, month, 1).getDay() + 6) % 7   // จันทร์ = 0
  const count = Math.ceil((first + dim) / 7) * 7
  return Array.from({ length: count }, (_, i) => {
    const d = i - first + 1
    return d > 0 && d <= dim ? d : null
  })
}
