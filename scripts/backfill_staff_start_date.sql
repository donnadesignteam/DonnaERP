-- เติม "วันเริ่มงาน" (staff.start_date) ที่ตกหล่นตอนย้ายจาก Google Sheet → DB
-- ค่าที่ใช้ = คอลัมน์วันเริ่มงานในชีท HR แท็บ Master_Data (ตรวจแล้วตรงกับคนที่มีข้อมูลอยู่ใน DB ทุกคน)
--
-- ‼️ จำเป็นต่อการล็อกอินโหมดพนักงาน — รหัสผ่าน = วันและเดือนที่เริ่มงาน (เช่น 31/3/2024 → 313)
--    ใครที่ start_date ว่าง จะล็อกอินไม่ได้ (ระบบจะบอกว่า "ยังไม่มีวันเริ่มงานในระบบ")
--
-- ปลอดภัย: อัปเดตเฉพาะแถวที่ยังว่างอยู่ (WHERE start_date IS NULL) ของเดิมไม่ถูกทับ
-- รันที่ Supabase → SQL Editor

UPDATE staff AS s
SET    start_date = v.d
FROM (VALUES
  ('DN001', DATE '2022-01-17'),   -- ยุน
  ('DN002', DATE '2022-03-01'),   -- สู้
  ('DN010', DATE '2023-10-01'),   -- แพท
  ('DN014', DATE '2024-04-01'),   -- เฟิร์น
  ('DN015', DATE '2024-03-31'),   -- น็อต  → รหัสผ่าน 313
  ('DN017', DATE '2024-06-17'),   -- ซาน
  ('DN019', DATE '2025-02-10'),   -- วุ้นเส้น
  ('DN025', DATE '2025-11-02'),   -- แต้ว
  ('DN030', DATE '2025-10-02'),   -- ออม
  ('DN034', DATE '2026-01-27')    -- พงศ์
) AS v(code, d)
WHERE s.code = v.code
  AND s.start_date IS NULL;

-- เช็คผล: ควรเหลือแค่ DN035 (กาย) กับ DN036 (ปูน) ที่ไม่มีวันเริ่มงานทั้งในชีทและ DB
-- → ให้ HR กรอกเองที่หน้าเว็บ /staff/DN035 และ /staff/DN036 (ทั้งคู่ยังล็อกอินไม่ได้จนกว่าจะกรอก)
SELECT code, nickname, start_date
FROM   staff
WHERE  active AND start_date IS NULL
ORDER  BY code;
